#!/usr/bin/env python3
"""Garden continuity: private-aware inventory and source-pinned generated re-entry.

No third-party dependencies. Read-only GitHub API; optional local output only.
All state and deployment claims remain project-owned.
"""
import argparse
import json
import os
from pathlib import Path
import sys
from datetime import datetime, timezone
from urllib.error import HTTPError, URLError
from urllib.parse import quote, urlencode
from urllib.request import Request, urlopen

BASE = "https://api.github.com"


class GitHub:
    def __init__(self, token, base=BASE):
        if not token:
            raise ValueError("GitHub token required: set GH_TOKEN or GITHUB_TOKEN; public fallback disabled")
        self.token = token
        self.base = base.rstrip("/")

    def get(self, path, **params):
        url = self.base + path
        if params:
            url += "?" + urlencode(params)
        req = Request(url, headers={
            "Authorization": "Bearer " + self.token,
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "GHoT-garden-pulse/0.1",
        })
        try:
            with urlopen(req, timeout=20) as resp:
                return json.load(resp)
        except (HTTPError, URLError) as exc:
            raise RuntimeError(f"GitHub read failed: {path}, {getattr(exc, 'code', type(exc).__name__)}") from exc

    def pages(self, path, **params):
        page = 1
        while True:
            items = self.get(path, per_page=100, page=page, **params)
            if not isinstance(items, list):
                raise ValueError(f"Unexpected GitHub collection: {path}")
            yield from items
            if len(items) < 100:
                return
            page += 1
            if page > 1000:
                raise RuntimeError("Refusing unbounded GitHub pagination")


def inventory(api, owner):
    """Include private repositories by default; record visible scope, never imply completeness."""
    owner_lower = owner.lower()
    items = api.pages("/user/repos", affiliation="owner,collaborator,organization_member", sort="updated")
    repos = {}
    for repo in items:
        if repo.get("owner", {}).get("login", "").lower() != owner_lower:
            continue
        full = repo["full_name"]
        repos[full.lower()] = {
            "full_name": full,
            "visibility": repo.get("visibility", "unknown"),
            "default_branch": repo.get("default_branch"),
            "html_url": repo.get("html_url"),
            "updated_at": repo.get("updated_at"),
        }
    return {
        "observed_at": datetime.now(timezone.utc).isoformat(),
        "owner": owner,
        "scope": "VISIBLE_TO_SUPPLIED_TOKEN_ONLY; INCLUDES_ACCESSIBLE_PRIVATE; NOT_ALL_GITHUB",
        "repositories": sorted(repos.values(), key=lambda x: x["full_name"].lower()),
    }


def safe(text):
    """Treat external metadata as text, not markdown control characters."""
    return str(text).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ").replace("\r", " ").replace("[", "\\[").replace("]", "\\]")


def generate(api, owner, name, intent):
    """Generate a replaceable view. Do not infer deployed/field-tested from GitHub."""
    slug = quote(owner, safe="") + "/" + quote(name, safe="")
    repo = api.get("/repos/" + slug)
    branch = repo.get("default_branch")
    if not branch:
        raise ValueError("Repository has no default branch")
    # Ignore this workflow's own generated-file commits. Using the actual
    # branch HEAD here creates an infinite cron → commit → new HEAD loop.
    commits = (c for c in api.pages("/repos/" + slug + "/commits", sha=branch)
               if not c.get("commit", {}).get("message", "").startswith(
                   "chore(continuity): refresh source-linked"))
    source_commit = next(commits, None)
    head = source_commit["sha"] if source_commit else "UNKNOWN"
    open_prs = list(api.pages("/repos/" + slug + "/pulls", state="open", sort="updated", direction="desc"))
    recent_closed = api.get("/repos/" + slug + "/pulls", state="closed", sort="updated", direction="desc", per_page=30)
    recent_merged = [p for p in recent_closed if p.get("merged_at")][:8]
    # Stable event cut: identical source state yields identical output.
    # Do not commit an artificial change every two hours just to refresh a clock.
    event_times = [source_commit.get("commit", {}).get("committer", {}).get("date", "") if source_commit else ""]
    event_times += [p.get("updated_at", "") for p in open_prs]
    event_times += [p.get("merged_at", "") for p in recent_merged]
    event_cut = max((x for x in event_times if x), default="UNKNOWN")
    visibility = repo.get("visibility", "unknown").upper()
    lines = [
        f"# {safe(intent.get('project', name))} — CONTINUE",
        "",
        "> GENERATED VIEW — do not edit this file by hand. Refresh using `garden/pulse.py`.",
        "> Source intent: `garden/intent.json`; current GitHub observations are not deployment proof.",
        "",
        f"- Most recent visible source event: `{event_cut}` (NOT a last-check timestamp)",
        f"- Visibility: **{visibility}** (preserve source access controls)",
        f"- Repo: `{safe(repo.get('full_name', owner + '/' + name))}`",
        f"- Last non-pulse code commit on `{safe(branch)}`: [`{head[:12]}`]({repo.get('html_url', '')}/commit/{head}) (not necessarily actual branch HEAD)",
        f"- Open PRs: **{len(open_prs)}**; recently merged sample: **{len(recent_merged)}**",
        "- Deployment: **UNKNOWN** (not examined by this tool)",
        "- Real-device / field proof: **UNKNOWN** (requires its own receipt)",
        "",
        "## Purpose / invariant goal",
        "",
        safe(intent.get("purpose", "UNKNOWN — project owner must supply intent")),
        "",
        "## Foundations (owner-written, not inferred)",
        "",
    ]
    for x in intent.get("foundations", []):
        lines.append(f"- **{safe(x['id'])}** [{safe(x.get('status', 'UNCLASSIFIED'))}]: {safe(x['text'])} — source: {safe(x.get('source', 'UNLINKED'))}")
    if not intent.get("foundations"):
        lines.append("- UNKNOWN — add source-linked foundations to `garden/intent.json`.")
    lines.extend(["", "## Open pull requests (live observations)", ""])
    if not open_prs:
        lines.append("- None visible to the supplied token at this check.")
    for pr in open_prs[:20]:
        lines.append(f"- [#{pr['number']}]({pr['html_url']}): {safe(pr['title'])} — **{'DRAFT' if pr.get('draft') else 'OPEN'}**; updated `{pr.get('updated_at', 'unknown')}`")
    if len(open_prs) > 20:
        lines.append(f"- … {len(open_prs)-20} more open PRs; query GitHub for the rest.")
    lines.extend(["", "## Recently merged (sample, NOT exhaustive)", ""])
    if not recent_merged:
        lines.append("- None found in the latest 30 closed PRs. This does not mean none exist.")
    for pr in recent_merged:
        lines.append(f"- [#{pr['number']}]({pr['html_url']}): {safe(pr['title'])}; merged `{pr['merged_at']}`")
    lines.extend(["", "## Current next move (owner-written)", "", safe(intent.get("next", "UNKNOWN — inspect project receipts")), "", "## Still fogged", ""])
    for x in intent.get("unknowns", []):
        lines.append("- " + safe(x))
    if not intent.get("unknowns"):
        lines.append("- No unknowns listed; this is not evidence that there are none.")
    lines.extend(["", "## Re-entry rule", "", "Read `AGENTS.md`, verify this view against current owner sources and original tests, then act. A merged PR is not a deployment; a deployment is not a field test. Rejected or superseded decisions stay linked, not silently erased.", ""])
    return "\n".join(lines)


def write_private(path, content):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(content)
    os.chmod(path, 0o600)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["inventory", "pulse"])
    parser.add_argument("--owner", default="the-static-collective")
    parser.add_argument("--repo", help="Repository name for pulse")
    parser.add_argument("--intent", default="garden/intent.json")
    parser.add_argument("--out", help="Local path for generated output")
    args = parser.parse_args(argv)
    api = GitHub(os.getenv("GH_TOKEN") or os.getenv("GITHUB_TOKEN"))
    if args.mode == "inventory":
        result = inventory(api, args.owner)
        counts = {v: sum(r["visibility"] == v for r in result["repositories"]) for v in ("public", "private", "unknown")}
        print(f"Authenticated, bounded inventory: {len(result['repositories'])} repos; {counts}. Private included if token permits.")
        if args.out:
            write_private(args.out, json.dumps(result, indent=2) + "\n")
            print("Private-capable inventory written to local restricted file (do not publish).")
    else:
        if not args.repo:
            parser.error("--repo required for pulse")
        with open(args.intent, encoding="utf-8") as f:
            intent = json.load(f)
        result = generate(api, args.owner, args.repo, intent)
        if args.out:
            write_private(args.out, result)
            print("Generated", args.out)
        else:
            print(result)
    return 0


if __name__ == "__main__":
    sys.exit(main())
